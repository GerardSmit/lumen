SUBJECTS = ['', 'a', 'aaa', 'abc', 'ab', 'Abc ABC', 'foo bar 123', 'a\nb\n', 'abab', 'aaab', 'xyz', '  a b\tc\n', 'éßKK', 'a1_b2', 'abcabc', '(a)', 'a-b', 'ab\n']
import re
import zlib


def err(e):
    pos = getattr(e, 'pos', None)
    return 'ERR %s %s %s' % (type(e).__name__, e.args[0] if e.args else '', pos)


def mdesc(m):
    if m is None:
        return None
    return (m.span(), m.groups(), m.lastindex, m.lastgroup, m.regs)


def attempt(f):
    try:
        return f()
    except Exception as e:
        return err(e)


def run(p, flags, out):
    try:
        c = re.compile(p, flags)
    except Exception as e:
        out.append(err(e))
        return
    out.append(repr((c.groups, c.flags, sorted(c.groupindex.items()), repr(c))))
    isb = isinstance(p, bytes)
    for s in SUBJECTS[:9]:
        if isb:
            s = s.encode('utf-8')
        out.append(repr(s))
        out.append(repr(attempt(lambda: mdesc(c.match(s)))))
        out.append(repr(attempt(lambda: mdesc(c.search(s)))))
        out.append(repr(attempt(lambda: mdesc(c.fullmatch(s)))))
        out.append(repr(attempt(lambda: c.findall(s))))
        out.append(repr(attempt(lambda: c.split(s))))
        out.append(repr(attempt(lambda: [mdesc(m) for m in c.finditer(s)])))
        rep = b'<\\g<0>>' if isb else '<\\g<0>>'
        out.append(repr(attempt(lambda: c.sub(rep, s))))
        rep1 = b'[\\1]' if isb else '[\\1]'
        out.append(repr(attempt(lambda: c.subn(rep1, s))))
        out.append(repr(attempt(lambda: c.sub(lambda m: str(m.span()) if not isb else b'x', s, 2))))


def main():
    import warnings
    warnings.simplefilter('ignore')
    for p in PATTERNS:
        for flags in (0, re.I | re.M | re.S):
            out = []
            run(p, flags, out)
            print('%r f%d %d %08x %s' % (p, flags, len(out), zlib.crc32('\n'.join(out).encode('utf-8', 'surrogatepass')), out[0][:60] if out[0].startswith('ERR') else ''))


main()
