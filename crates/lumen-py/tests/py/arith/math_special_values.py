# math functions at special values and their CPython error classes.
import math

inf, nan = math.inf, math.nan


def t(f, *a):
    try:
        print(f.__name__, a, repr(f(*a)))
    except Exception as e:
        print(f.__name__, a, type(e).__name__, e)


for f in (math.cos, math.sin, math.tan):
    t(f, inf)
    t(f, -inf)
t(math.atanh, 1.0)
t(math.atanh, -1.0)
t(math.atanh, -0.0)
t(math.acosh, 0.5)
t(math.asinh, -0.0)
t(math.lgamma, 0.0)
t(math.lgamma, -2.0)
t(math.lgamma, inf)
t(math.gamma, 0.0)
t(math.gamma, -1.0)
t(math.gamma, 0.5)
t(math.gamma, 172.0)
t(math.gamma, -inf)
t(math.exp, 1000.0)
t(math.exp, -inf)
t(math.sqrt, -1.0)
t(math.log, 0)
t(math.log, 0.0)
t(math.log, -1)
t(math.log, 2 ** 2000)
t(math.log2, 2 ** 2000)
t(math.log10, 10 ** 400)
t(math.log1p, -1.0)
t(math.fmod, 5.0, inf)
t(math.fmod, inf, 1.0)
t(math.remainder, 5.0, 2.0)
t(math.remainder, 7.0, 2.0)
t(math.remainder, -0.0, 1.0)
t(math.remainder, 1.0, 0.0)
t(math.erf, 0.5)
t(math.erfc, 30.0)
t(math.dist, [1e200], [-1e200])
t(math.dist, [1e308, 1e308], [-1e308, -1e308])
t(math.hypot, 1e200, 1e200)
t(math.hypot, 3, 4, 12)
t(math.hypot, inf, nan)
t(math.hypot, nan, 1.0)
t(math.fsum, [1e308, 1e308])
t(math.fsum, [inf, -inf])
t(math.fsum, [1e100, 1.0, -1e100, 1e-100, 1e50, -1.0, -1e50])
t(math.fsum, [0.1] * 10)
t(math.fsum, [-0.0, -0.0])
t(math.fsum, [])
t(math.ldexp, 0.75, 1024)
t(math.ldexp, 1.0, -1075)
t(math.ldexp, 1.0, 2 ** 100)
t(math.ldexp, 1.0, -(2 ** 100))
t(math.ldexp, 0.0, 2 ** 100)
t(math.frexp, 5e-324)
t(math.frexp, 1.7976931348623157e308)
t(math.frexp, -0.0)
t(math.frexp, inf)
t(math.cosh, 1000.0)
t(math.sinh, -1000.0)
t(math.pow, 0.0, -1.0)
t(math.pow, -8.0, 1 / 3)
t(math.exp2, 1024.0)
t(math.expm1, 1000.0)
