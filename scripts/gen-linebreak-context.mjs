// Unicode 15 contextual properties missing from unicode-linebreak 0.1.5.
// Usage: node scripts/gen-linebreak-context.mjs CORPUS_DIR [--verify]
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const [root, verify] = process.argv.slice(2);
if (!root || (verify && verify !== '--verify')) throw Error('expected CORPUS_DIR [--verify]');
const files = ['EastAsianWidth.txt', 'emoji/emoji-data.txt', 'UnicodeData.txt'];
const sources = files.map(file => readFileSync(join(root, file), 'utf8'));
const assigned = new Uint8Array(0x110000);
let first;
for (const line of sources[2].split('\n')) {
  if (!line) continue;
  const [code, name] = line.split(';');
  const cp = parseInt(code, 16);
  if (name.endsWith(', First>')) first = cp;
  else if (name.endsWith(', Last>')) { assigned.fill(1, first, cp + 1); first = undefined; }
  else assigned[cp] = 1;
}
function property(source, accept) {
  const flags = new Uint8Array(0x110000);
  for (const raw of source.split('\n')) {
    const line = raw.split('#')[0].trim();
    if (!line) continue;
    const [range, value] = line.split(';').map(v => v.trim());
    if (!accept(value)) continue;
    const [start, end = start] = range.split('..').map(v => parseInt(v, 16));
    flags.fill(1, start, end + 1);
  }
  return flags;
}
function ranges(name, flags) {
  const lines = [`pub(super) const ${name}: &[(u32, u32)] = &[`];
  for (let start = 0; start < flags.length; start++) {
    if (!flags[start]) continue;
    let end = start;
    while (flags[end + 1]) end++;
    lines.push(`    (0x${start.toString(16)}, 0x${end.toString(16)}),`);
    start = end;
  }
  return lines.concat('];').join('\n');
}
const wide = property(sources[0], value => ['F', 'W', 'H'].includes(value));
const pictographic = property(sources[1], value => value === 'Extended_Pictographic');
for (let cp = 0; cp < pictographic.length; cp++) pictographic[cp] &= !assigned[cp];
let output = '// GENERATED by scripts/gen-linebreak-context.mjs; Unicode 15.0.0.\n';
output += '// Unicode data: https://www.unicode.org/Public/15.0.0/ucd/\n';
output += '// Terms: https://www.unicode.org/terms_of_use.html\n';
files.forEach((file, i) => { output += `// ${file}: sha256 ${createHash('sha256').update(sources[i]).digest('hex')}\n`; });
output += '\n' + ranges('WIDE', wide) + '\n\n' + ranges('UNASSIGNED_PICTOGRAPHIC', pictographic) + '\n';
const destination = fileURLToPath(new URL('../crates/lumen-common/src/linebreak_context.rs', import.meta.url));
if (verify) {
  if (readFileSync(destination, 'utf8') !== output) throw Error('linebreak_context.rs is stale');
} else writeFileSync(destination, output);
